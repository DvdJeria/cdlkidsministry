-- ============================================================================
-- CDL Kids Ministry - Esquema de Base de Datos (PostgreSQL / Supabase)
-- Esquema: public
-- Ordenado por dependencias de claves foráneas para ejecución directa.
-- ============================================================================

-- 1. Niveles o cursos del ministerio infantil
CREATE TABLE IF NOT EXISTS public.cursos (
  cur_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cur_nombre character varying(120) NOT NULL
);

COMMENT ON TABLE public.cursos IS 'Niveles o grupos de clases disponibles en CDL Kids.';
COMMENT ON COLUMN public.cursos.cur_id IS 'Identificador único del curso.';
COMMENT ON COLUMN public.cursos.cur_nombre IS 'Nombre visible del nivel o curso.';

-- 2. Maestros responsables de clase
CREATE TABLE IF NOT EXISTS public.maestros (
  ma_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ma_nombre character varying(120) NOT NULL,
  ma_apellido character varying(120) NOT NULL,
  is_deleted boolean NOT NULL DEFAULT false
);

COMMENT ON TABLE public.maestros IS 'Catálogo de maestros; usa borrado lógico mediante is_deleted.';
COMMENT ON COLUMN public.maestros.is_deleted IS 'Indica si el maestro está dado de baja (true) o activo (false).';

-- 3. Niños registrados por curso
CREATE TABLE IF NOT EXISTS public.ninos (
  ni_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ni_nombre character varying(120) NOT NULL,
  ni_apellido character varying(120) NOT NULL,
  cur_id integer REFERENCES public.cursos (cur_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  is_deleted boolean NOT NULL DEFAULT false
);

COMMENT ON TABLE public.ninos IS 'Padrón de niños asociados a un curso; usa borrado lógico mediante is_deleted.';
COMMENT ON COLUMN public.ninos.cur_id IS 'Curso o nivel asignado al niño.';
COMMENT ON COLUMN public.ninos.is_deleted IS 'Indica si el registro está inactivo/eliminado lógicamente.';

CREATE INDEX IF NOT EXISTS idx_ninos_cur_id ON public.ninos (cur_id);
CREATE INDEX IF NOT EXISTS idx_ninos_is_deleted ON public.ninos (is_deleted);

-- 4. Cabecera de cada jornada o registro de clase
CREATE TABLE IF NOT EXISTS public.registros_clase (
  reg_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cur_id integer REFERENCES public.cursos (cur_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  ma_id integer REFERENCES public.maestros (ma_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  fecha date NOT NULL,
  observacion_general text
);

COMMENT ON TABLE public.registros_clase IS 'Sesión o jornada de clase registrada para un curso y maestro en una fecha.';
COMMENT ON COLUMN public.registros_clase.observacion_general IS 'Comentario o novedad general reportada por el maestro.';

CREATE INDEX IF NOT EXISTS idx_registros_clase_cur_id ON public.registros_clase (cur_id);
CREATE INDEX IF NOT EXISTS idx_registros_clase_ma_id ON public.registros_clase (ma_id);
CREATE INDEX IF NOT EXISTS idx_registros_clase_fecha ON public.registros_clase (fecha);

-- 5. Detalle de asistencia y Biblia por niño en cada clase
CREATE TABLE IF NOT EXISTS public.asistencias (
  asi_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reg_id integer REFERENCES public.registros_clase (reg_id) ON UPDATE CASCADE ON DELETE CASCADE,
  ni_id integer REFERENCES public.ninos (ni_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  presente boolean NOT NULL DEFAULT false,
  trajo_biblia boolean NOT NULL DEFAULT false
);

COMMENT ON TABLE public.asistencias IS 'Registro individual de asistencia y porte de Biblia por sesión de clase.';
COMMENT ON COLUMN public.asistencias.presente IS 'Indica si el niño asistió a la clase.';
COMMENT ON COLUMN public.asistencias.trajo_biblia IS 'Indica si el niño llevó su Biblia a la clase.';

CREATE INDEX IF NOT EXISTS idx_asistencias_reg_id ON public.asistencias (reg_id);
CREATE INDEX IF NOT EXISTS idx_asistencias_ni_id ON public.asistencias (ni_id);